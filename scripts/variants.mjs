#!/usr/bin/env node
// Design version manager. Zero tokens: runs without Claude.
//
// The tree is version-first — a version is a design generation (e.g. "App V3",
// "App V2") and owns whichever pages exist inside it:
//
//   src/variants/<version>/<page>/index.tsx
//
// So a page only offers itself under versions that actually contain it, and
// saving snapshots a whole version rather than a single screen.
//
// Usage:
//   npm run variant -- save <version> <new-id> "<note>" [--force]
//   npm run variant -- add-version <id> "<Label>" [from] ["<note>"]
//   npm run variant -- add-page <version> <page-id> "<Label>" ["<Group>"]
//   npm run variant -- delete-version <id>
//   npm run variant -- delete-page <version> <page-id>
//   npm run variant -- rename-version <old-id> <new-id> ["<Label>"]
//   npm run variant -- rename-page <old-id> <new-id> ["<Label>"]
//   npm run variant -- list
//   npm run variant -- sync
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const VARIANTS = fs.existsSync(path.join(ROOT, "src", "variants"))
  ? path.join(ROOT, "src", "variants")
  : path.join(ROOT, "variants");
const REGISTRY = path.join(VARIANTS, "registry.json");
const MANIFEST = path.join(VARIANTS, "manifest.ts");

const die = (msg) => { console.error(`x ${msg}`); process.exit(1); };
const ok = (msg) => console.log(`ok ${msg}`);
const isSlug = (s) => /^[a-z0-9]+(-[a-z0-9]+)*$/.test(s);
const ident = (s) => s.replace(/-/g, "_");

/* fs.renameSync is atomic but throws EPERM on Windows when a watcher (the dev
   server) holds a handle on the folder. Fall back to copy-then-remove. */
function moveDir(src, dst) {
  try {
    fs.renameSync(src, dst);
  } catch (err) {
    if (err.code !== "EPERM" && err.code !== "EACCES" && err.code !== "EXDEV") throw err;
    fs.cpSync(src, dst, { recursive: true });
    fs.rmSync(src, { recursive: true, force: true });
  }
}

function load() {
  if (!fs.existsSync(REGISTRY)) die("variants/registry.json not found. Run this from the project root.");
  return JSON.parse(fs.readFileSync(REGISTRY, "utf8"));
}

function write(reg) {
  fs.writeFileSync(REGISTRY, JSON.stringify(reg, null, 2) + "\n");
  sync(reg);
}

/** Which pages actually exist on disk under a version, in registry order. */
function pagesIn(reg, versionId) {
  const dir = path.join(VARIANTS, versionId);
  if (!fs.existsSync(dir)) return [];
  return Object.keys(reg.pages).filter((p) =>
    fs.existsSync(path.join(dir, p, "index.tsx")),
  );
}

function sync(reg) {
  const lines = [
    "// AUTO-GENERATED by scripts/variants.mjs. Do not edit.",
    'import type { ComponentType } from "react";',
  ];
  const entries = [];
  const byVersion = [];

  for (const v of reg.versions) {
    const pages = pagesIn(reg, v.id);
    if (!pages.length) {
      console.warn(`! ${v.id} has no pages on disk, skipped`);
      continue;
    }
    for (const p of pages) {
      const name = `${ident(v.id)}__${ident(p)}`;
      lines.push(`import ${name} from "./${v.id}/${p}";`);
      entries.push(`  "${v.id}/${p}": ${name},`);
    }
    byVersion.push(`  "${v.id}": [${pages.map((p) => `"${p}"`).join(", ")}],`);
  }

  lines.push(
    "",
    "export const components: Record<string, ComponentType> = {",
    ...entries,
    "};",
    "",
    "/** Pages that exist in each version, so the picker only offers real screens. */",
    "export const pagesByVersion: Record<string, string[]> = {",
    ...byVersion,
    "};",
    "",
  );
  fs.writeFileSync(MANIFEST, lines.join("\n"));
}

const STUB = (label, comp) => `export default function ${comp}() {
  return (
    <main className="min-h-screen p-24">
      <h1 className="text-h4">${label}</h1>
    </main>
  );
}
`;

const [cmd, ...rest] = process.argv.slice(2);
const force = rest.includes("--force");
const args = rest.filter((a) => a !== "--force");

switch (cmd) {
  /* Snapshot a whole version. This is the history entry: nothing is
     overwritten, so an older save stays reachable from the picker. */
  case "save": {
    const [from, id, note] = args;
    if (!from || !id) die('Usage: save <version> <new-id> "<note>"');
    if (!note || !note.trim()) die("A note is required. No note, no save.");
    if (!isSlug(id)) die(`"${id}" must be lowercase kebab-case, e.g. app-v3-dense`);
    const reg = load();
    if (!reg.versions.some((v) => v.id === from)) die(`Unknown version "${from}"`);
    if (from === id) die("Source and target are the same");
    const src = path.join(VARIANTS, from);
    const dst = path.join(VARIANTS, id);
    if (!fs.existsSync(src)) die(`Source version ${from} not found on disk`);
    const exists = reg.versions.some((v) => v.id === id);
    if (exists && !force) die(`${id} already exists. Add --force to overwrite.`);
    fs.rmSync(dst, { recursive: true, force: true });
    fs.cpSync(src, dst, { recursive: true });
    reg.versions = reg.versions.filter((v) => v.id !== id);
    reg.versions.push({
      id,
      label: id,
      note: note.trim(),
      from,
      createdAt: new Date().toISOString(),
    });
    write(reg);
    ok(`Saved ${id}: ${note.trim()}`);
    console.log(`   Preview: /preview?version=${id}`);
    break;
  }

  case "add-version": {
    const [id, label, from, note] = args;
    if (!id || !label) die('Usage: add-version <id> "<Label>" [from] ["<note>"]');
    if (!isSlug(id)) die(`"${id}" must be lowercase kebab-case`);
    const reg = load();
    if (reg.versions.some((v) => v.id === id)) die(`Version "${id}" already exists`);
    const dst = path.join(VARIANTS, id);
    if (from) {
      const src = path.join(VARIANTS, from);
      if (!fs.existsSync(src)) die(`Source version ${from} not found`);
      fs.cpSync(src, dst, { recursive: true });
    } else {
      fs.mkdirSync(dst, { recursive: true });
    }
    reg.versions.push({
      id,
      label: label.trim(),
      note: (note || (from ? `Copied from ${from}` : "New version")).trim(),
      from: from || null,
      createdAt: new Date().toISOString(),
    });
    write(reg);
    ok(`Added version ${id}${from ? ` from ${from}` : ""}`);
    break;
  }

  case "add-page": {
    const [version, id, label, group = "app"] = args;
    if (!version || !id || !label) die('Usage: add-page <version> <page-id> "<Label>" ["<Group>"]');
    if (!isSlug(id)) die(`"${id}" must be lowercase kebab-case`);
    const reg = load();
    if (!reg.versions.some((v) => v.id === version)) die(`Unknown version "${version}"`);
    const dir = path.join(VARIANTS, version, id);
    if (fs.existsSync(dir)) die(`${version}/${id} already exists`);
    fs.mkdirSync(dir, { recursive: true });
    const comp = (label.replace(/[^A-Za-z0-9]/g, "") || "Page") + "Page";
    fs.writeFileSync(path.join(dir, "index.tsx"), STUB(label, comp));
    reg.pages[id] = reg.pages[id] ?? { label: label.trim(), group };
    write(reg);
    ok(`Added page ${version}/${id}`);
    break;
  }

  case "delete-version": {
    const [id] = args;
    if (!id) die("Usage: delete-version <id>");
    const reg = load();
    if (!reg.versions.some((v) => v.id === id)) die(`Version "${id}" not found`);
    if (reg.versions.filter((v) => !v.draft).length <= 1 && !reg.versions.find((v) => v.id === id)?.draft) {
      die("That is the last version — refusing to delete it");
    }
    fs.rmSync(path.join(VARIANTS, id), { recursive: true, force: true });
    reg.versions = reg.versions.filter((v) => v.id !== id);
    write(reg);
    ok(`Deleted version ${id}`);
    break;
  }

  case "delete-page": {
    const [version, id] = args;
    if (!version || !id) die("Usage: delete-page <version> <page-id>");
    const reg = load();
    const dir = path.join(VARIANTS, version, id);
    if (!fs.existsSync(dir)) die(`${version}/${id} not found`);
    fs.rmSync(dir, { recursive: true, force: true });
    // Drop the label only once no version still carries the page.
    const stillUsed = reg.versions.some((v) => pagesIn(reg, v.id).includes(id));
    if (!stillUsed) delete reg.pages[id];
    write(reg);
    ok(`Deleted ${version}/${id}`);
    break;
  }

  case "rename-version": {
    const [from, to, label] = args;
    if (!from || !to) die('Usage: rename-version <old-id> <new-id> ["<Label>"]');
    if (!isSlug(to)) die(`"${to}" must be lowercase kebab-case`);
    const reg = load();
    const entry = reg.versions.find((v) => v.id === from);
    if (!entry) die(`Version "${from}" not found`);
    if (from !== to) {
      if (reg.versions.some((v) => v.id === to)) die(`Version "${to}" already exists`);
      moveDir(path.join(VARIANTS, from), path.join(VARIANTS, to));
      entry.id = to;
      // Keep lineage readable for anything saved from the old name.
      reg.versions.forEach((v) => { if (v.from === from) v.from = to; });
    }
    if (label && label.trim()) entry.label = label.trim();
    write(reg);
    ok(`Renamed version ${from} to ${to}`);
    break;
  }

  /* A page id is shared across versions, so renaming moves the folder
     wherever it exists rather than only in one version. */
  case "rename-page": {
    const [from, to, label] = args;
    if (!from || !to) die('Usage: rename-page <old-id> <new-id> ["<Label>"]');
    if (!isSlug(to)) die(`"${to}" must be lowercase kebab-case`);
    const reg = load();
    if (!reg.pages[from]) die(`Page "${from}" not found`);
    if (from !== to && reg.pages[to]) die(`Page "${to}" already exists`);
    if (from !== to) {
      for (const v of reg.versions) {
        const src = path.join(VARIANTS, v.id, from);
        if (fs.existsSync(src)) moveDir(src, path.join(VARIANTS, v.id, to));
      }
      reg.pages[to] = reg.pages[from];
      delete reg.pages[from];
    }
    if (label && label.trim()) reg.pages[to].label = label.trim();
    write(reg);
    ok(`Renamed page ${from} to ${to}`);
    break;
  }

  case "list": {
    const reg = load();
    for (const v of reg.versions) {
      const pages = pagesIn(reg, v.id);
      const when = new Date(v.createdAt).toISOString().slice(0, 10);
      console.log(`\n${v.label} (${v.id})${v.draft ? "  [draft]" : ""}  ${when}`);
      console.log(`  ${v.note}`);
      console.log(`  pages: ${pages.length ? pages.join(", ") : "(none)"}`);
    }
    break;
  }

  case "sync":
    sync(load());
    ok("Manifest regenerated");
    break;

  default:
    console.log(
      "Commands: save | add-version | add-page | delete-version | delete-page | rename-version | rename-page | list | sync",
    );
}
